/* ── 평가서 HTML 생성 ───────────────────────────── */
const REVIEW_MARK = {
  O: { label: '그대로 좋음', cls: 'good', sym: '○' },
  '△': { label: '다듬으면 좋음', cls: 'warn', sym: '△' },
  X: { label: '고쳐야 함', cls: 'bad', sym: '✕' }
};

function reviewHTML(id) {
  const R = REVIEWS[id];
  if (!R) return '';

  const counts = { O: 0, '△': 0, X: 0 };
  REVIEW_CRITERIA.forEach((c) => { counts[R.marks[c.key].m]++; });

  return `
  <article class="rv" style="--c:${R.color}">
    <header class="rv-head">
      <div class="rv-kicker">AI 기획 평가서</div>
      <h2><span class="rv-emoji">${R.emoji}</span>${R.title}</h2>
      <div class="rv-who">기획 : ${R.who}</div>
      <div class="rv-score">
        <span class="rv-pill good">○ ${counts.O}</span>
        <span class="rv-pill warn">△ ${counts['△']}</span>
        <span class="rv-pill bad">✕ ${counts.X}</span>
      </div>
    </header>

    <p class="rv-summary">${R.summary}</p>

    <section class="rv-sec">
      <h3>항목별 평가</h3>
      <table class="rv-table">
        <thead>
          <tr><th style="width:34px"></th><th style="width:150px">항목</th><th>판정 근거</th></tr>
        </thead>
        <tbody>
          ${REVIEW_CRITERIA.map((c) => {
            const m = R.marks[c.key];
            const K = REVIEW_MARK[m.m];
            return `<tr>
              <td class="rv-mark ${K.cls}">${K.sym}</td>
              <td class="rv-name">${c.name}<span>${c.desc}</span></td>
              <td class="rv-note">${m.note}</td>
            </tr>`;
          }).join('')}
        </tbody>
      </table>
    </section>

    <section class="rv-sec">
      <h3>기획서에 없어서 내가 정한 값</h3>
      <p class="rv-lead">아래 값은 원래 기획자의 몫입니다. 조절실에서 바꾸면 그대로 반영됩니다.</p>
      <table class="rv-table tight">
        <thead><tr><th style="width:38%">빠져 있던 항목</th><th style="width:24%">내가 정한 값</th><th>이유</th></tr></thead>
        <tbody>
          ${R.missing.map((m) => `<tr><td>${m.item}</td><td class="rv-mono">${m.decided}</td><td class="rv-note">${m.why}</td></tr>`).join('')}
        </tbody>
      </table>
    </section>

    <section class="rv-sec">
      <h3>디버깅 목록</h3>
      ${R.bugs.map((b) => `
        <div class="rv-bug">
          <div class="rv-bug-head">
            <span class="rv-lv lv${b.level}">${b.level}순위</span>
            <b>${b.title}</b>
          </div>
          <div class="rv-row"><span class="rv-k">테스트에서 나온 값</span><span class="rv-v">${b.found}</span></div>
          <div class="rv-row"><span class="rv-k">왜 문제인가</span><span class="rv-v">${b.why}</span></div>
          <div class="rv-fix">
            <span class="rv-k">이 순서로 고쳐 보세요</span>
            <ol>${b.fix.map((f) => `<li>${f}</li>`).join('')}</ol>
          </div>
        </div>`).join('')}
    </section>
  </article>`;
}
